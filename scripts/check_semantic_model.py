"""Check real local semantic embeddings using illustrative text, without saving a corpus."""

import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from equitylens.config import Settings
from equitylens.live.rag import LocalEmbedder, Passage, SessionIndex

texts = [
    ("cash", "Cash generated by operating activities improved liquidity and funded working capital."),
    ("factory", "The manufacturer opened a vehicle assembly plant and increased production capacity."),
    ("debt", "Long-term borrowings were repaid, reducing interest expense and leverage."),
]
passages = [
    Passage(
        id=key + ":C001",
        source_id=key,
        title="Illustrative business excerpt",
        text=value,
        url="https://example.com",
        locator="Illustration",
        evidence_level="search_excerpt",
        category="research",
        publisher="Illustration",
        published_at=None,
        retrieved_at=datetime.now(UTC).isoformat(),
    )
    for key, value in texts
]
index = SessionIndex(passages, LocalEmbedder(Settings()))
assert index.summary()["mode"] == "hybrid_semantic_bm25", index.summary()
for question, expected in [
    ("How is the business financing day-to-day operations?", "cash"),
    ("Where did the enterprise expand its manufacturing facilities?", "factory"),
    ("Has the firm lowered its borrowing burden?", "debt"),
]:
    result = index.search(question, top_k=1)
    assert result and result[0]["source_id"] == expected, (question, result)
    print(
        {
            "semantic_paraphrase": expected,
            "top_source": result[0]["source_id"],
            "similarity": result[0]["semantic_score"],
        }
    )
irrelevant = index.search("Give me a recipe for chocolate cake", top_k=2)
print(
    {
        "unrelated_query_hits": len(irrelevant),
        "model": index.summary()["model"],
        "dimensions": index.summary()["dimensions"],
    }
)
index.clear()
assert not index.passages and index.vectors is None
print("Local semantic model and explicit index cleanup verified.")
