class TinyEmbedder:
    model_name = "test-semantic-fixture"

    def _vector(self, text):
        text = text.lower()
        return np.array(
            [
                1 + 4 * any(x in text for x in ["cash", "liquidity", "operating activities"]),
                1 + 4 * any(x in text for x in ["factory", "manufacturing"]),
                1 + 4 * any(x in text for x in ["debt", "borrowings"]),
            ],
            dtype=np.float32,
        )

    def documents(self, texts):
        return np.stack([self._vector(text) for text in texts])

    def query(self, text):
        return self._vector(text)


def source(sid="S1", text="The company increased cash generated by operating activities."):
    return Evidence(
        id=sid,
        title="Company report",
        url="https://example.com/report",
        publisher="Example",
        retrieved_at=datetime.now(UTC),
        category="research",
        content=text,
        evidence_level="search_excerpt",
    )


def passage(sid, text):
    return Passage(
        id=f"{sid}:C001",
        source_id=sid,
        title="Report",
        text=text,
        url="https://example.com/report",
        locator="HTML block 1",
        evidence_level="page_excerpt",
        category="research",
        publisher="Example",
        published_at=None,
        retrieved_at=datetime.now(UTC).isoformat(),
    )


def test_chunking_retains_source_and_location():
    text = "Long financial statement discussion. " * 60
    chunks = chunk_blocks(source(), [{"text": text, "locator": "PDF page 7"}])
    assert len(chunks) > 1
    assert chunks[0].id == "S1:C001"
    assert chunks[0].source_id == "S1"
    assert chunks[0].text[-150:] == chunks[1].text[:150]
    assert chunks[0].locator.startswith("PDF page 7")
    assert max(len(p.text) for p in chunks) <= 750


