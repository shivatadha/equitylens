def test_readable_page_is_used_without_fabricating_headline_body(tmp_path):
    async def fetch(url):
        if url.endswith("robots.txt"):
            return 404, {}, b""
        return (
            200,
            {"content-type": "text/html"},
            b"<main><p>Operating activities generated substantial cash and improved liquidity.</p></main>",
        )

    async def extractor(data, kind):
        return extract(data, kind)

    settings = Settings(database_url="", data_dir=tmp_path, _env_file=None)
    pipeline = RagPipeline(settings, TinyEmbedder(), PublicReader(fetch, extractor))
    company = CompanyMatch(
        symbol="ACME", name="Acme", exchange="NASDAQ", market="US", retrieved_at=datetime.now(UTC)
    )
    bundle = asyncio.run(pipeline.build(company, [source()], [], None, "quick"))
    hits = bundle["index"].search("operating liquidity", top_k=1)
    assert hits[0]["evidence_level"] == "page_excerpt"
    assert hits[0]["locator"].startswith("HTML block")
    assert bundle["summary"]["body_sources_read"] == 1
    assert not list(tmp_path.iterdir())


def test_official_feed_document_takes_read_priority_over_search_excerpts(tmp_path):
    read_ids = []

    class Reader:
        async def read(self, item):
            read_ids.append(item.id)
            return {"source_id": item.id, "status": "read", "blocks": [{"text": item.content, "locator": "PDF page 1"}], "notice": ""}

    settings = Settings(database_url="", data_dir=tmp_path, _env_file=None)
    pipeline = RagPipeline(settings, TinyEmbedder(), Reader())
    excerpts = [source(f"S{i}") for i in range(1, 4)]
    official = source("NSE1", "The exchange posted a company filing about a new project.")
    official.evidence_level = "official_feed_summary"
    official.category = "official_announcement"
    company = CompanyMatch(
        symbol="ACME.NS", name="Acme", exchange="NSE", market="IN", retrieved_at=datetime.now(UTC)
    )
    bundle = asyncio.run(pipeline.build(company, excerpts + [official], [], None, "quick"))
    assert "NSE1" in read_ids
    assert len(read_ids) == 2
    assert bundle["summary"]["body_sources_read"] == 2


def test_model_receives_only_retrieved_passages_and_unknown_citations_are_dropped(tmp_path):
    captured = []

    class Provider:
        async def synthesize(self, company, evidence, metrics, model, question=None):
            captured.append([e.id for e in evidence])
            return {
                "sections": [
                    {
                        "title": "Answer",
                        "claims": [
                            {"text": "Retrieved observation.", "source_ids": [evidence[0].id]},
                            {"text": "Invented observation.", "source_ids": ["NOT-RETRIEVED"]},
                        ],
                    }
                ]
            }

    settings = Settings(database_url="", data_dir=tmp_path, llm_api_key="fixture-key", _env_file=None)
    service = ResearchService(settings, Provider(), RagPipeline(settings, TinyEmbedder()))
    index = SessionIndex(
        [passage(f"S{i}", f"Cash flow observation number {i} increases liquidity.") for i in range(1, 12)],
        TinyEmbedder(),
    )
    company = CompanyMatch(
        symbol="ACME", name="Acme", exchange="NASDAQ", market="US", retrieved_at=datetime.now(UTC)
    )
    sid, secret = service.sessions.create(
        {"company": company.model_dump(mode="json"), "evidence": [], "calculations": []}, index
    )
    with TestClient(create_app(settings, service)) as client:
        response = client.post(
            f"/live/sessions/{sid}/follow-up",
            headers={"Authorization": "Bearer " + secret},
            json={"question": "How does cash generation affect liquidity?", "llm_model": "fixture"},
        )
        assert response.status_code == 200, response.text
        result = response.json()
        assert len(captured[0]) <= 6
        assert captured[0] == [p["id"] for p in result["matches"]]
        assert len(result["analysis"][0]["claims"]) == 1
        assert client.post(f"/live/sessions/{sid}/retrieve", json={"question": "cash"}).status_code == 401
        assert (
            client.post(
                f"/live/sessions/{sid}/retrieve",
                headers={"Authorization": "Bearer wrong"},
                json={"question": "cash"},
            ).status_code
            == 404
        )


def test_missing_future_period_returns_cited_coverage_gap(tmp_path):
    settings = Settings(database_url="", data_dir=tmp_path, llm_api_key="", _env_file=None)
    service = ResearchService(settings, rag=RagPipeline(settings, TinyEmbedder()))
    financial = replace(
        passage("F1", "Operating cash flow: 100 USD. Reporting period 12M, ended 2025-06-30."),
        category="financial",
        evidence_level="structured_fact",
    )
    index = SessionIndex([financial], TinyEmbedder())
    company = CompanyMatch(
        symbol="ACME", name="Acme", exchange="NASDAQ", market="US", retrieved_at=datetime.now(UTC)
    )
    sid, token = service.sessions.create(
        {"company": company.model_dump(mode="json"), "evidence": [], "calculations": []}, index
    )
    answer = asyncio.run(service.follow_up(sid, token, "What was operating cash flow in FY2035?"))
    assert answer["failure_code"] is None
    assert answer["analysis"][0]["claims"][0]["source_ids"] == ["F1:C001"]
    assert "does not cover" in answer["analysis"][0]["claims"][0]["text"]
