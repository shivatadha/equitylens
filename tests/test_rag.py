def test_connection_pins_public_ip_and_blocks_mixed_dns():
    connected = []

    class Delegate:
        async def connect_tcp(self, host, port, **kwargs):
            connected.append(host)
            return "stream"

    async def public(host, port):
        return ["93.184.216.34"]

    backend = PublicNetworkBackend(Delegate(), public)
    assert asyncio.run(backend.connect_tcp("example.com", 443)) == "stream"
    assert connected == ["93.184.216.34"]

    async def mixed(host, port):
        return ["93.184.216.34", "127.0.0.1"]

    with pytest.raises(ValueError):
        asyncio.run(PublicNetworkBackend(Delegate(), mixed).connect_tcp("example.com", 443))


def test_robots_disallow_prevents_body_fetch():
    fetched = []

    async def fetch(url):
        fetched.append(url)
        return 200, {}, b"User-agent: *\nDisallow: /"

    result = asyncio.run(PublicReader(fetch=fetch).read(source()))
    assert result["status"] == "robots_denied"
    assert fetched == ["https://example.com/robots.txt"]


def test_redirect_to_private_address_is_not_followed():
    fetched = []

    async def fetch(url):
        fetched.append(url)
        if url.endswith("robots.txt"):
            return 404, {}, b""
        return 302, {"location": "https://127.0.0.1/secret"}, b""

    result = asyncio.run(PublicReader(fetch=fetch).read(source()))
    assert result["status"] == "unavailable"
    assert not any("127.0.0.1" in url for url in fetched)


