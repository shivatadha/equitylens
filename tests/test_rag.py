def test_semantic_retrieval_finds_paraphrase():
    index = SessionIndex(
        [
            passage("S1", "Cash generated from operating activities increased."),
            passage("S2", "A manufacturing factory opened."),
            passage("S3", "Debt and borrowings decreased."),
        ],
        TinyEmbedder(),
    )
    hits = index.search("Describe operating liquidity", top_k=1)
    assert hits[0]["source_id"] == "S1"
    assert hits[0]["semantic_score"] > 0.9
    assert index.summary()["mode"] == "hybrid_semantic_bm25"


