def test_context_budget_and_source_diversity():
    chunks = [passage("S1", "Cash operating cash flow. " * 20) for _ in range(8)] + [
        passage("S2", "Debt cash repayment. " * 20)
    ]
    index = SessionIndex(chunks, TinyEmbedder())
    hits = index.search("cash", top_k=10, max_chars=2000)
    assert sum(len(p["text"]) for p in hits) <= 2000
    assert sum(p["source_id"] == "S1" for p in hits) <= 2


def test_index_expiry_and_deletion_remove_vectors():
    clock = [0]
    index = SessionIndex([passage("S1", "Operating cash generation improved.")], TinyEmbedder(), ["acme"])
    vector_reference = index.vectors
    store = SessionStore(ttl=10, clock=lambda: clock[0])
    sid, secret = store.create({}, index)
    assert store.get_index(sid, secret) is index
    clock[0] = 11
    store.purge()
    assert not index.passages
    assert index.vectors is None
    assert not index.ignored_tokens
    assert not vector_reference.any()
    with pytest.raises(KeyError):
        store.get_index(sid, secret)


def test_bm25_fallback_is_explicit_and_can_abstain():
    class Offline(TinyEmbedder):
        def documents(self, texts):
            raise OSError("Model missing")

    index = SessionIndex([passage("S1", "Operating cash generation improved.")], Offline())
    assert index.summary()["mode"] == "bm25_only"
    assert "unavailable" in index.notice
    assert index.search("cash")
    assert index.search("volcano eruption") == []


